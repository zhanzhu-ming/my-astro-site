-- Run this in Supabase SQL Editor.
-- The browser receives only the anon/publishable key. Never expose service_role keys.
create table if not exists public.inquiries (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  company text not null,
  email text not null,
  phone text,
  interest text not null,
  quantity text,
  market text,
  message text,
  language text not null default 'en',
  consent boolean not null default false
);

alter table public.inquiries enable row level security;

-- Public visitors may submit inquiries only. They cannot read, update or delete rows.
drop policy if exists "Allow public inquiry submissions" on public.inquiries;
create policy "Allow public inquiry submissions"
on public.inquiries for insert
to anon, authenticated
with check (
  consent = true
  and length(trim(name)) between 1 and 120
  and length(trim(company)) between 1 and 160
  and length(trim(email)) between 3 and 254
  and length(trim(interest)) between 1 and 200
);

grant insert on public.inquiries to anon, authenticated;
grant usage, select on sequence public.inquiries_id_seq to anon, authenticated;
