-- Run this in the Supabase SQL Editor.
-- The browser receives only the anon/publishable key. Never expose service_role keys.

create table if not exists public.inquiries (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  company text not null,
  email text not null,
  phone text,
  country text,
  interest text not null,
  quantity text,
  specification text,
  application text,
  market text,
  documents text,
  message text,
  source_page text,
  inquiry_type text not null default 'general',
  language text not null default 'en',
  consent boolean not null default false
);

-- 已有项目升级：保留历史数据，仅补充新字段。
alter table public.inquiries add column if not exists country text;
alter table public.inquiries add column if not exists specification text;
alter table public.inquiries add column if not exists application text;
alter table public.inquiries add column if not exists documents text;
alter table public.inquiries add column if not exists source_page text;
alter table public.inquiries add column if not exists inquiry_type text not null default 'general';

create index if not exists inquiries_created_at_idx on public.inquiries (created_at desc);
create index if not exists inquiries_product_idx on public.inquiries (interest);

alter table public.inquiries enable row level security;

-- Public visitors may submit inquiries only. They cannot read, update or delete rows.
drop policy if exists "Allow public inquiry submissions" on public.inquiries;
create policy "Allow public inquiry submissions"
on public.inquiries for insert
to anon, authenticated
with check (
  consent = true
  and length(trim(name)) between 1 and 120
  and length(trim(company)) between 1 and 160
  and length(trim(email)) between 3 and 254
  and length(trim(interest)) between 1 and 200
);

grant insert on public.inquiries to anon, authenticated;
grant usage, select on sequence public.inquiries_id_seq to anon, authenticated;

